"""Real Splash regression for complete legacy parameters and durable receipts.

Uses synthetic historical state generated by the actual 0.3.0 bundle, plus
fresh current requests. This does not invoke a Provider or official Shell Agent.
"""
import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import business_test_driver as driver

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "experiments/source-bridge/fixtures/legacy-receipt.json"


def run(bundle, output, binary):
    driver.configure(bundle, output, binary, legacy_vm_fixture=True)
    checks = []
    calls = 0

    def batch(name, state, *requests):
        nonlocal calls
        calls += len(requests)
        raw = driver.run(name, list(requests), state)
        results = []
        for index in range(len(requests)):
            assert raw[index].get("ok") is True, (name, index, raw[index])
            results.append(raw[index]["data"])
        return results

    state = output / "current-state"
    request = driver.save("complete-current", title="合成完整字段", amount="45", flow_names=["合成兼容分组"])
    created, = batch("complete-save", state, request)
    assert created["ok"] and not created["replayed"]
    before = driver.latest(state)
    assert len(before["records"]) == len(before["receipts"]) == 1
    record_id = created["record_id"]
    assert before["records"][0]["id"] == record_id and before["records"][0]["cents"] == 4500
    checks.append("complete legacy fields save and return success with matching durable record")

    replay, readback = batch("restart-replay", state, request, driver.query(record_id=record_id))
    assert replay["ok"] and replay["replayed"] and replay["record_id"] == record_id
    assert readback["total"] == 1 and readback["records"][0]["cents"] == 4500
    assert driver.latest(state) == before
    checks.append("same request across restart replays with no database or receipt change")

    changed = deepcopy(request); changed["args"]["amount"] = "46"
    denied, = batch("changed-payload", state, changed)
    assert not denied["ok"] and driver.latest(state) == before
    checks.append("changed payload with same request ID is rejected without writes")

    apply_state = output / "apply-state"
    apply_request = deepcopy(request); apply_request["name"] = "dailyflow.apply"
    result, = batch("complete-apply", apply_state, apply_request)
    assert result["ok"] and len(driver.latest(apply_state)["records"]) == 1
    checks.append("complete parameters also return success through dailyflow.apply")

    minimal = {"name": "dailyflow.apply", "args": {"request_id": "minimal-modern", "kind": "expense", "title": "合成精简字段", "date": driver.DAY, "amount": "2"}}
    result, = batch("minimal-modern", apply_state, minimal)
    assert result["ok"] and len(driver.latest(apply_state)["records"]) == 2
    checks.append("modern minimal arguments still use current contract")

    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    old = fixture["state"]
    historical = output / "historical-state"
    folder = historical / "dailyflow"; folder.mkdir(parents=True)
    (folder / "state-a.json").write_text(json.dumps(old, ensure_ascii=False), encoding="utf-8")
    replay, readback = batch("historical-replay", historical, fixture["request"], driver.query())
    assert replay["ok"] and replay["replayed"]
    after = driver.latest(historical)
    assert len(after["records"]) == len(old["records"]) == 1
    assert readback["total"] == 1 and readback["records"][0]["cents"] == old["records"][0]["cents"]
    assert after["records"][0]["id"] == old["records"][0]["id"] == replay["record_id"]
    assert after["receipts"] == old["receipts"]
    checks.append("actual historical 0.3.0 receipt replays preserving ID, amount and receipt bytes")

    replay, = batch("historical-repeat", historical, fixture["request"])
    assert replay["replayed"] and driver.latest(historical) == after
    changed = deepcopy(fixture["request"]); changed["args"]["amount"] = "11"
    denied, = batch("historical-changed-payload", historical, changed)
    assert not denied["ok"] and driver.latest(historical) == after
    checks.append("historical repeated read is stable and changed payload cannot overwrite")

    report = dict(passed=True, tool_calls=calls, checks=checks,
                  evidence_kind="real legacy Splash VM with explicit isolated manifest fixture; synthetic data",
                  legacy_vm_fixture=driver.fixture_metadata(),
                  official_shell_agent=False, real_provider=False,
                  historical_fixture_sha256=hashlib.sha256(FIXTURE.read_bytes()).hexdigest(),
                  tested_bundle=str(bundle),
                  tested_bundle_main_sha256=hashlib.sha256((bundle / "main.splash").read_bytes()).hexdigest())
    (output / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, default=ROOT / "bundle")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--binary", type=Path, required=True)
    args = parser.parse_args()
    run(args.bundle.resolve(), args.output.resolve(), args.binary.resolve())
